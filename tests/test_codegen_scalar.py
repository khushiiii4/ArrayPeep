def compile_source(source: str) -> list[Quad]:
    program = parse(source)
    analyze(program)
    return generate_code(program)


def quads_of(source: str) -> list[tuple]:
    return [(q.op, q.arg1, q.arg2, q.result) for q in compile_source(source)]


# -- test-local reference evaluators ---------------------------------------------------


def eval_ast(program: ast.Program) -> dict[str, int]:
    """Final scalars of a scalar-only program, evaluated directly on the AST."""
    env: dict[str, int] = {}
    loop_names: set[str] = set()

    def expr(e):
        if isinstance(e, ast.Number):
            return e.value
        if isinstance(e, ast.ScalarRef):
            return env.get(e.name, 0)
        if isinstance(e, ast.UnaryMinus):
            return -expr(e.operand)
        a, b = expr(e.left), expr(e.right)
        return a + b if e.op == "+" else a - b if e.op == "-" else a * b

    def run(items):
        for item in items:
            if isinstance(item, ast.Assign):
                env[item.target.name] = expr(item.value)
            elif isinstance(item, ast.ForLoop):
                loop_names.add(item.var)
                for v in range(item.lo, item.hi + 1):
                    env[item.var] = v
                    run(item.body)

    run(program.items)
    return {k: v for k, v in env.items() if k not in loop_names}


def run_quads(quads: list[Quad]) -> tuple[dict[str, int], int]:
    """(final scalars, dynamic quadruple count) by the rules of quad_spec.md Section 3.1."""
    match, stack = {}, []
    for pc, q in enumerate(quads):
        if q.op == "FOR":
            stack.append(pc)
        elif q.op == "ENDFOR":
            match[stack.pop()] = pc
    end_to_for = {v: k for k, v in match.items()}
    env: dict[str, int] = {}
    loop_names = {q.arg1 for q in quads if q.op == "FOR"}

    def val(x):
        return x if isinstance(x, int) else env.get(x, 0)

    pc, executed = 0, 0
    while pc < len(quads):
        q = quads[pc]
        executed += 1
        if q.op == "FOR":
            if q.arg2 <= q.result:
                env[q.arg1] = q.arg2
                pc += 1
            else:
                pc = match[pc] + 1  # zero-trip loop: skip body and ENDFOR
            continue
        if q.op == "ENDFOR":
            start = end_to_for[pc]
            if env[q.arg1] < quads[start].result:
                env[q.arg1] += 1
                pc = start + 1
            else:
                pc += 1
            continue
        if q.op == ":=":
            env[q.result] = val(q.arg1)
        else:
            a, b = val(q.arg1), val(q.arg2)
            env[q.result] = a + b if q.op == "+" else a - b if q.op == "-" else a * b
        pc += 1
    scalars = {k: v for k, v in env.items() if k not in loop_names and not is_temp(k)}
    return scalars, executed


