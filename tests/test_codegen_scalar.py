class QuadRecordTests(unittest.TestCase):
    def test_fields_and_default_tag(self) -> None:
        q = Quad("+", "s", 1, "T1")
        self.assertEqual((q.op, q.arg1, q.arg2, q.result, q.tag), ("+", "s", 1, "T1", "BODY"))
        self.assertEqual(Quad("ENDFOR", "i").arg2, None)

    def test_tags(self) -> None:
        self.assertEqual((TAG_ADDR, TAG_BODY), ("ADDR", "BODY"))
        self.assertEqual(Quad("+", 1, 2, "T1", TAG_ADDR).tag, "ADDR")

    def test_immutable_and_comparable(self) -> None:
        q = Quad("*", "i", 2, "T1")
        with self.assertRaises(Exception):
            q.op = "+"  # type: ignore[misc]
        self.assertEqual(q, Quad("*", "i", 2, "T1"))
        self.assertNotEqual(q, Quad("*", "i", 2, "T1", TAG_ADDR))
        self.assertEqual(len({q, Quad("*", "i", 2, "T1")}), 1)

    def test_invalid_records_are_rejected(self) -> None:
        for bad in [lambda: Quad("%", 1, 2, "T1"), lambda: Quad("+", 1, 2, "T1", "MAYBE"),
                    lambda: Quad("+", 1.5, 2, "T1"), lambda: Quad("+", True, 2, "T1"),
                    lambda: Quad("+", [1], 2, "T1")]:
            with self.assertRaises(ValueError):
                bad()

    def test_negative_literals_are_allowed(self) -> None:
        self.assertEqual(Quad("FOR", "i", -2, 2).arg2, -2)

    def test_temp_name_predicates(self) -> None:
        self.assertTrue(is_temp("T1") and is_temp("T12"))
        self.assertFalse(any(is_temp(x) for x in ["T", "P1", "t1", "T1a", "x", 5, None]))
        self.assertTrue(is_addr_temp("P1") and is_addr_temp("P20"))
        self.assertFalse(any(is_addr_temp(x) for x in ["P", "T1", "p1", 3, None]))


class ListingPrinterTests(unittest.TestCase):
    def test_matches_the_roadmap_listing(self) -> None:
        listing = format_listing(compile_source("for i = 1 to 3 do s = s + i * 2; end"))
        self.assertEqual(
            [line.split() for line in listing.splitlines()],
            [["1", "BODY", "FOR", "i", "1", "3"],
             ["2", "BODY", "*", "i", "2", "T1"],
             ["3", "BODY", "+", "s", "T1", "T2"],
             ["4", "BODY", ":=", "T2", "-", "s"],
             ["5", "BODY", "ENDFOR", "i"]],
        )

    def test_sample_layout_of_quad_spec_9_2(self) -> None:
        quads = [Quad("FOR", "i", 1, 10), Quad("*", "i", 20, "T1"), Quad(":=", "T1", None, "s"),
                 Quad("ENDFOR", "i")]
        self.assertEqual(
            format_listing(quads).splitlines(),
            ["  1  BODY  FOR     i        1        10",
             "  2  BODY  *       i        20       T1",
             "  3  BODY  :=      T1       -        s",
             "  4  BODY  ENDFOR  i"],
        )

    def test_address_tag_is_printed(self) -> None:
        self.assertEqual(format_listing([Quad("+", "T1", "j", "T2", TAG_ADDR)]),
                         "  1  ADDR  +       T1       j        T2")

    def test_title_header_is_74_wide(self) -> None:
        text = format_listing([Quad(":=", 0, None, "s")], title="Quadruples (L1)")
        header, first = text.splitlines()
        self.assertEqual(len(header), LISTING_WIDTH)
        self.assertEqual(LISTING_WIDTH, 74)
        self.assertTrue(header.startswith("== Quadruples (L1) =") and header.endswith("="))
        self.assertEqual(first, "  1  BODY  :=      0        -        s")

    def test_empty_listing(self) -> None:
        self.assertEqual(format_listing([]), "")
        self.assertEqual(format_listing([], title="Quadruples").count("\n"), 0)

    def test_no_trailing_whitespace_or_newline(self) -> None:
        text = format_listing(compile_source("for i = 1 to 2 do s = s + 1; end"))
        self.assertFalse(text.endswith("\n"))
        for line in text.splitlines():
            self.assertEqual(line, line.rstrip())

    def test_wide_operands_widen_the_columns_and_stay_aligned(self) -> None:
        quads = [Quad("+", "a_rather_long_name", 123456789, "T1"), Quad(":=", "T1", None, "s")]
        a, b = format_listing(quads).splitlines()
        self.assertEqual(a.index("123456789"), b.index("-"))
        self.assertEqual(a.index("T1"), b.index("s"))
        self.assertEqual(a.split(), ["1", "BODY", "+", "a_rather_long_name", "123456789", "T1"])

    def test_negative_literals(self) -> None:
        self.assertEqual(format_listing([Quad("FOR", "i", -2, 2)]),
                         "  1  BODY  FOR     i        -2       2")

    def test_line_numbers_are_right_aligned(self) -> None:
        quads = [Quad(":=", 0, None, "s")] * 100
        lines = format_listing(quads).splitlines()
        self.assertTrue(lines[8].startswith("  9  ") and lines[9].startswith(" 10  "))
        self.assertTrue(lines[99].startswith("100  "))


